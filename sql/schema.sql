CREATE DATABASE IF NOT EXISTS controle_ti CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE controle_ti;

CREATE TABLE IF NOT EXISTS usuarios (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  senha_hash VARCHAR(255) NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS setores (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL UNIQUE,
  responsavel VARCHAR(100) NOT NULL,
  localizacao VARCHAR(100) NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS equipamentos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  tipo ENUM('COMPUTADOR','NOTEBOOK','IMPRESSORA','MONITOR','REDE','SERVIDOR','PERIFERICO','OUTRO') NOT NULL,
  numero_patrimonio VARCHAR(30) NOT NULL UNIQUE,
  marca VARCHAR(60) NOT NULL,
  modelo VARCHAR(60) NOT NULL,
  numero_serie VARCHAR(60) NULL,
  status ENUM('ATIVO','EM_MANUTENCAO','INATIVO','BAIXADO') NOT NULL DEFAULT 'ATIVO',
  data_aquisicao DATE NULL,
  observacoes TEXT NULL,
  setor_id INT NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_equip_setor FOREIGN KEY (setor_id) REFERENCES setores(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS manutencoes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  equipamento_id INT NOT NULL,
  usuario_id INT NOT NULL,
  tipo ENUM('PREVENTIVA','CORRETIVA') NOT NULL,
  descricao VARCHAR(500) NOT NULL,
  status ENUM('ABERTA','CONCLUIDA') NOT NULL DEFAULT 'ABERTA',
  custo DECIMAL(10,2) NULL,
  data_abertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  data_conclusao TIMESTAMP NULL,
  CONSTRAINT fk_manut_equip FOREIGN KEY (equipamento_id) REFERENCES equipamentos(id) ON DELETE RESTRICT,
  CONSTRAINT fk_manut_user FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE RESTRICT
);

CREATE INDEX idx_equip_status ON equipamentos(status);
CREATE INDEX idx_equip_setor ON equipamentos(setor_id);
CREATE INDEX idx_manut_equip ON manutencoes(equipamento_id);
